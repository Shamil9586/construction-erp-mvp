-- Integrity-fix migration (2026-09-15, п.5): BitrixInstallation получает
-- поле для хранения референсного application_token (зашифрованного, той же
-- схемой AES-256-GCM, что и access/refresh токены — см. crypto.util.ts).
--
-- Согласно официальной документации Bitrix24 (apidocs.bitrix24.com,
-- раздел "Локальные приложения" / ONAPPINSTALL), application_token,
-- полученный при установке приложения, должен сохраняться и в дальнейшем
-- сверяться (вместе с member_id) во входящих запросах последующих
-- event-хендлеров как признак того, что запрос действительно пришёл от
-- того же портала, который ранее установил приложение. Раньше это поле
-- в схеме отсутствовало, и application_token из ONAPPINSTALL после
-- проверки присутствия отбрасывался — сверять future-запросы было не с
-- чем.
--
-- Это НЕ делает самый первый вызов ONAPPINSTALL криптографически
-- подтверждённым (см. комментарий в install.controller.ts и
-- docs/bitrix24-integration.md §2 — REQUIRES BITRIX24 TEST PORTAL
-- VERIFICATION остаётся в силе для самого первого контакта) — это лишь
-- даёт возможность подтверждать ПОСЛЕДУЮЩИЕ вызовы тем же эталоном.
--
-- Столбец nullable: у записей, созданных до этой миграции, эталонного
-- значения нет (это ожидаемо, не ошибка данных).
-- ============================================================================

ALTER TABLE "BitrixInstallation" ADD COLUMN "encryptedApplicationToken" TEXT;
